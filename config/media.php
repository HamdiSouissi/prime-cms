            'mp4' => ['video/mp4'],
            'webm' => ['video/webm', 'audio/webm'],
        ],
        'archive' => [
            'zip' => ['application/zip', 'application/x-zip-compressed'],
        ],
    ],

    /**
     * Named responsive image sizes generated by `Prime\Media\ImageProcessor`.
     * Extensible via the `media.image_sizes` filter.
     *
     * - `crop => true` crops around the media item's focal point (`focal_x`, `focal_y`).
     * - `crop => false` scales proportionally to fit within `width` (and `height` when non-null).
     * - Upscaling is never performed: sizes larger than the source image are skipped.
     */
    'image_sizes' => [
        'thumbnail' => ['width' => 150, 'height' => 150, 'crop' => true],
        'small' => ['width' => 480, 'height' => null, 'crop' => false],
        'medium' => ['width' => 960, 'height' => null, 'crop' => false],
        'large' => ['width' => 1600, 'height' => null, 'crop' => false],
    ],
];
