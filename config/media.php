<?php

declare(strict_types=1);

use Prime\Kernel\Env;

/**
 * Prime CMS Media Library configuration (Phase 7).
 *
 * SVG uploads are intentionally DISABLED by default: SVG is an executable XML format
 * capable of carrying embedded `<script>`, `<foreignObject>`, and event-handler XSS
 * payloads. Sites that require SVG uploads must attach a strict server-side XML sanitizer
 * and explicitly opt in via the `media.allowed_types` filter.
 */
return [
    // Relative paths inside the project root
    'uploads_dir' => 'content/uploads',
    'public_link' => 'public/uploads',
    'url_prefix' => '/uploads',

    // Upload limits (effective max size is min(max_upload_mb, PHP upload_max_filesize, PHP post_max_size))
    'max_upload_mb' => max(1, (int) Env::get('MEDIA_MAX_UPLOAD_MB', 20)),
    'max_megapixels' => max(1, (int) Env::get('MEDIA_MAX_MEGAPIXELS', 40)),
    'max_dimension' => max(320, (int) Env::get('MEDIA_MAX_DIMENSION', 2560)),

    // Encoding quality (1-100)
    'webp_quality' => max(1, min(100, (int) Env::get('MEDIA_WEBP_QUALITY', 82))),
    'jpeg_quality' => max(1, min(100, (int) Env::get('MEDIA_JPEG_QUALITY', 85))),

    /**
     * Allowed file types grouped by logical kind => [extension => list of accepted real MIME types].
     * Extensible via the `media.allowed_types` filter.
     *
     * Note: `avif` is automatically enabled only when the host GD extension supports AVIF.
     * Note: `svg` is intentionally absent by default for XSS defense-in-depth.
     */
    'allowed_types' => [
        'image' => [
            'jpg' => ['image/jpeg'],
            'jpeg' => ['image/jpeg'],
            'png' => ['image/png'],
            'gif' => ['image/gif'],
            'webp' => ['image/webp'],
            'avif' => ['image/avif'],
        ],
        'document' => [
            'pdf' => ['application/pdf'],
            'docx' => [
                'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
                'application/zip',
            ],
            'xlsx' => [
                'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
                'application/zip',
            ],
            'pptx' => [
                'application/vnd.openxmlformats-officedocument.presentationml.presentation',
                'application/zip',
            ],
            'odt' => ['application/vnd.oasis.opendocument.text'],
            'ods' => ['application/vnd.oasis.opendocument.spreadsheet'],
            'txt' => ['text/plain'],
            'csv' => ['text/csv', 'text/plain', 'application/csv'],
        ],
        'audio' => [
            'mp3' => ['audio/mpeg', 'audio/mp3'],
            'ogg' => ['audio/ogg', 'application/ogg'],
            'wav' => ['audio/wav', 'audio/x-wav', 'audio/wave'],
