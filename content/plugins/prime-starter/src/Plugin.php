<?php

declare(strict_types=1);

namespace PrimeStarter;

use Prime\Admin\AdminContext;
use Prime\Admin\Menu\AdminMenu;
use Prime\Admin\Menu\MenuItem;
use Prime\Admin\Notice;
use Prime\Auth\Auth;
use Prime\Content\ContentType;
use Prime\Editor\BlockDefinition;
use Prime\Http\Router;
use Prime\Jobs\JobHandlerRegistry;
use Prime\Jobs\JobQueue;
use Prime\Plugins\AbstractPlugin;
use Prime\Plugins\PluginContext;
use Prime\Scheduler\Schedule;
use Prime\Security\HtmlSanitizer;
use Prime\Settings\SettingsRegistry;
use Prime\Site\PageContext;
use Prime\Themes\ThemeAssetRegistry;
use PrimeStarter\Api\NotesApi;
use PrimeStarter\Controller\NotesController;
use PrimeStarter\Jobs\DigestJob;
use Throwable;

/**
 * Prime Starter — the plugin `make:plugin` copies, and a tour of every extension point.
 *
 * Each numbered section uses one public API and nothing else; delete the ones you do not need.
 * The feature is small on purpose: a notebook of Markdown notes, managed in the admin, readable
 * on the site and through the REST API, summarised by a weekly e-mail.
 */
final class Plugin extends AbstractPlugin
{
    public const SLUG = 'prime-starter';

    public const CAPABILITY = 'prime_starter.manage';

    public const BLOCK_MARKDOWN = 'prime-starter/markdown';

    public const DYNAMIC_BLOCK = 'prime_starter_notes';

    public const EDITOR = 'prime-starter-markdown';

    public const JOB_DIGEST = 'prime-starter.digest';

    public const TASK_DIGEST = 'prime-starter.weekly-digest';

    public const PUBLIC_PATH = '/notes';

    public function register(PluginContext $context): void
    {
        // 1. Capability, granted through « Utilisateurs › Rôles » (administrators hold `*`).
        $context->capabilities()->register(self::CAPABILITY, 'plugin::prime-starter.capability');

        // 2. Settings section on « Réglages › Général », generated by the settings API.
        $context->hooks()->filter('settings.register', static function (mixed $registry): mixed {
            if ($registry instanceof SettingsRegistry) {
                self::registerSettings($registry);
            }

            return $registry;
        });

        // 3. Services: plain constructors, wired once in the container.
        $container = $context->app()->container();
        $container->singleton(NoteRepository::class, static fn (): NoteRepository => new NoteRepository($context->db()));
        $container->singleton(NotesController::class, static fn (): NotesController => new NotesController(
            $context,
            $context->app()->get(NoteRepository::class),
            $context->app()->get(AdminContext::class),
            $context->app()->get(Auth::class),
        ));
        $container->singleton(NotesApi::class, static fn (): NotesApi => new NotesApi($context->app()->get(NoteRepository::class)));

        // 4. Admin: menu entry, stylesheet and routes under `/admin/prime-starter`.
        $context->hooks()->filter('admin.menu', static function (mixed $menu): mixed {
            if ($menu instanceof AdminMenu) {
                $menu->add(new MenuItem(
                    id: 'plugin.prime-starter',
                    label: 'plugin::prime-starter.menu',
                    icon: 'file-text',
                    url: '/admin/prime-starter',
                    position: 61,
                    accent: 'teal',
                    capability: self::CAPABILITY,
                    group: 'admin.menu.groups.system',
                ));
            }

            return $menu;
        });
        $context->hooks()->filter('admin.assets', static function (mixed $assets) use ($context): mixed {
            if (is_array($assets) && isset($assets['css']) && is_array($assets['css'])) {
                $assets['css'][] = $context->url('css/admin.css');
            }

            return $assets;
        });
        $context->router()->adminGroup(static function (Router $r): void {
            $r->get('/', [NotesController::class, 'index'])->name('index');
            $r->get('/new', [NotesController::class, 'create'])->name('create');
            $r->post('/notes', [NotesController::class, 'store'])->name('store');
            $r->get('/notes/{id:\d+}/edit', [NotesController::class, 'edit'])->name('edit');
            $r->post('/notes/{id:\d+}', [NotesController::class, 'update'])->name('update');
            $r->post('/notes/{id:\d+}/delete', [NotesController::class, 'destroy'])->name('destroy');
        }, capability: self::CAPABILITY);
        $context->setSettingsUrl('/admin/prime-starter');

        // 5. Public page `/notes`, rendered inside the active theme, with its own stylesheet.
        $context->router()->frontGroup(static function (Router $r): void {
            $r->get(self::PUBLIC_PATH, [NotesController::class, 'publicIndex'])->name('public');
        });
        $context->hooks()->on('site.assets', static function (mixed $assets, mixed $page = null) use ($context): void {
            $onNotes = $page instanceof PageContext && $page->isPlugin() && $page->path === self::PUBLIC_PATH;
            if ($assets instanceof ThemeAssetRegistry && $onNotes) {
                $assets->style('prime-starter', $context->url('css/public.css'));
            }
        });

        // 6. REST API under `/api/prime-starter/v1`: public reading, writing with the capability.
        self::registerApi($context);

        // 7. Prime Editor block: server validation and rendering, client module for the editor.
        $context->blocks()->register(new BlockDefinition(
            type: self::BLOCK_MARKDOWN,
            title: 'plugin::prime-starter.blocks.markdown.title',
            description: 'plugin::prime-starter.blocks.markdown.description',
            icon: 'file-text',
            category: 'plugins',
            validator: static function (array $data, HtmlSanitizer $sanitizer): array {
                $markdown = is_string($data['markdown'] ?? null) ? str_replace("\r\n", "\n", $data['markdown']) : '';
                $errors = mb_strlen($markdown) > NoteRepository::BODY_MAX
                    ? [t('plugin::prime-starter.validation.body_max', ['max' => NoteRepository::BODY_MAX])]
                    : [];

                return ['data' => ['markdown' => $markdown], 'errors' => $errors];
            },
            renderer: static function (array $data, HtmlSanitizer $sanitizer): string {
                $markdown = is_string($data['markdown'] ?? null) ? $data['markdown'] : '';

                return '<div class="pc-block pc-block--markdown">' . $sanitizer->sanitizeBasic(Markdown::toHtml($markdown)) . '</div>';
            },
            textExtractor: static fn (array $data): string => Markdown::toText(is_string($data['markdown'] ?? null) ? $data['markdown'] : ''),
            keywords: ['markdown', 'md', 'texte', 'text', 'note'],
        ));
        $context->blocks()->enqueueScript($context->url('js/markdown-block.js'));

        // 8. Dynamic block for theme zones (« Apparence › Zones »): the latest public notes.
        $context->hooks()->filter('blocks.dynamic', static function (mixed $blocks) use ($context): mixed {
            if (is_array($blocks)) {
                $blocks[self::DYNAMIC_BLOCK] = self::dynamicBlock($context);
            }

            return $blocks;
        });

        // 9. Alternative editor: posts are written in Markdown when the setting says so.
        $context->editors()->register(
            name: self::EDITOR,
            label: 'plugin::prime-starter.editor.label',
            render: static fn (array $state): string => $context->views()->render('prime-starter::admin/editor', [
                'markdown' => self::markdownFromDocument($state['document']),
                'contentJson' => $state['contentJson'],
            ]),
            scripts: ['js/markdown-editor.js'],
            styles: ['css/admin.css'],
        );
        $context->hooks()->filter('content.editor', static function (mixed $editor, mixed $type = null) use ($context): mixed {
            $enabled = (bool) $context->settings()->get('markdown_posts', false);

            return $enabled && $type instanceof ContentType && $type->name === 'post' ? self::EDITOR : $editor;
        });

        // 10. Queued job + scheduled task: a weekly digest of the notes that changed.
        $context->hooks()->filter('jobs.register_handlers', static function (mixed $registry) use ($context): mixed {
            if ($registry instanceof JobHandlerRegistry) {
                $registry->register(self::JOB_DIGEST, new DigestJob($context));
            }

            return $registry;
        });
        $context->hooks()->filter('scheduler.register', static function (mixed $schedule) use ($context): mixed {
            if ($schedule instanceof Schedule) {
                $schedule->call(
                    name: self::TASK_DIGEST,
                    action: static function () use ($context): void {
                        if (trim((string) $context->settings()->get('digest_email', '')) !== '') {
                            $context->app()->get(JobQueue::class)->dispatch(self::JOB_DIGEST, ['days' => 7]);
                        }
                    },
                    expression: '0 8 * * 1',
                    description: t('plugin::prime-starter.scheduler.digest'),
                    owner: self::SLUG,
                );
            }

            return $schedule;
        });

        // 11. A line in « Outils › État du système ».
        $context->hooks()->filter('system.checks', static function (mixed $checks) use ($context): mixed {
            if (!is_array($checks)) {
                return $checks;
            }

            $label = t('plugin::prime-starter.system.label');
            try {
                $count = $context->app()->get(NoteRepository::class)->count();
                $checks[] = ['id' => 'prime-starter.notes', 'group' => 'plugins', 'label' => $label, 'status' => 'ok', 'value' => tc('plugin::prime-starter.system.value', $count, ['count' => $count])];
            } catch (Throwable) {
                $checks[] = ['id' => 'prime-starter.notes', 'group' => 'plugins', 'label' => $label, 'status' => 'error', 'value' => t('plugin::prime-starter.system.table_missing')];
            }

            return $checks;
        });
    }

    public function activate(PluginContext $context): void
    {
        $context->notices()->add(
            id: 'welcome',
            type: Notice::TYPE_SUCCESS,
            title: 'plugin::prime-starter.notices.welcome.title',
            message: 'plugin::prime-starter.notices.welcome.message',
            actionLabel: 'plugin::prime-starter.notices.welcome.action',
            actionUrl: '/admin/prime-starter',
            capability: self::CAPABILITY,
            dismissible: true,
        );
    }

    public function deactivate(PluginContext $context): void
    {
        $context->notices()->remove('welcome');
    }

    public function uninstall(PluginContext $context): void
    {
        // The core drops the table (migrations), the `plugin.prime-starter.*` settings, the
        // capability on every role and token, the queued jobs and the scheduler stamps.
        $context->notices()->clearAll();
    }

    /**
     * Markdown held by the editor's block, or the text of a document written with Prime Editor.
     *
     * @param array<string, mixed> $document
     */
    public static function markdownFromDocument(array $document): string
    {
        $blocks = is_array($document['blocks'] ?? null) ? $document['blocks'] : [];
        $parts = [];
        foreach ($blocks as $block) {
            if (!is_array($block) || !is_array($block['data'] ?? null)) {
                continue;
            }
            $data = $block['data'];
            if (($block['type'] ?? null) === self::BLOCK_MARKDOWN && is_string($data['markdown'] ?? null)) {
                $parts[] = $data['markdown'];
            } elseif (is_string($data['text'] ?? null)) {
                $parts[] = trim(html_entity_decode(strip_tags($data['text']), ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            }
        }

        return implode("\n\n", array_filter($parts, static fn (string $part): bool => $part !== ''));
    }

    private static function registerSettings(SettingsRegistry $registry): void
    {
        $registry->section(self::SLUG, [
            'label' => 'plugin::prime-starter.settings.section_title',
            'description' => 'plugin::prime-starter.settings.section_description',
            'icon' => 'file-text',
            'priority' => 210,
            'page' => 'general',
        ]);
        $fields = [
            ['key' => 'public_enabled', 'type' => 'toggle', 'default' => true, 'rules' => '', 'priority' => 10],
            ['key' => 'public_title', 'type' => 'text', 'default' => 'Carnet', 'rules' => 'required|max:80', 'priority' => 20],
            ['key' => 'markdown_posts', 'type' => 'toggle', 'default' => false, 'rules' => '', 'priority' => 30],
            ['key' => 'digest_email', 'type' => 'email', 'default' => '', 'rules' => 'email|max:191', 'priority' => 40],
        ];
        foreach ($fields as $field) {
            $registry->add([
                'name' => 'plugin.' . self::SLUG . '.' . $field['key'],
                'label' => 'plugin::prime-starter.settings.' . $field['key'],
                'description' => 'plugin::prime-starter.settings.' . $field['key'] . '_help',
                'type' => $field['type'],
                'section' => self::SLUG,
                'default' => $field['default'],
                'rules' => $field['rules'],
                'priority' => $field['priority'],
            ], self::SLUG);
        }
    }

    private static function registerApi(PluginContext $context): void
    {
        $api = $context->api();
        $api->schema('PrimeStarterNote', [
            'type' => 'object',
            'properties' => [
                'id' => ['type' => 'integer'],
                'title' => ['type' => 'string'],
                'body' => ['type' => 'string', 'description' => 'Markdown'],
                'html' => ['type' => 'string'],
                'color' => ['type' => 'string', 'enum' => NoteRepository::COLORS],
                'pinned' => ['type' => 'boolean'],
                'public' => ['type' => 'boolean'],
                'updated_at' => ['type' => ['string', 'null'], 'format' => 'date-time'],
            ],
        ]);
        $note = ['type' => 'object', 'properties' => ['data' => ['$ref' => '#/components/schemas/PrimeStarterNote']]];
        $input = [
            'type' => 'object',
            'properties' => [
                'title' => ['type' => 'string', 'maxLength' => NoteRepository::TITLE_MAX],
                'body' => ['type' => 'string', 'maxLength' => NoteRepository::BODY_MAX],
                'color' => ['type' => 'string', 'enum' => NoteRepository::COLORS],
                'pinned' => ['type' => 'boolean'],
                'public' => ['type' => 'boolean'],
            ],
        ];

        $api->get('/notes', [NotesApi::class, 'index'], public: true, options: [
            'summary' => 'Public notes (every note with the capability)',
            'response' => ['type' => 'object', 'properties' => ['data' => ['type' => 'array', 'items' => ['$ref' => '#/components/schemas/PrimeStarterNote']]]],
        ]);
        $api->get('/notes/{id:\d+}', [NotesApi::class, 'show'], public: true, options: ['summary' => 'One note', 'response' => $note, 'errors' => [404]]);
        $api->post('/notes', [NotesApi::class, 'store'], permission: self::CAPABILITY, options: [
            'summary' => 'Create a note',
            'request' => ['required' => ['title']] + $input,
            'response' => $note,
            'errors' => [401, 403, 422],
        ]);
        $api->patch('/notes/{id:\d+}', [NotesApi::class, 'update'], permission: self::CAPABILITY, options: [
            'summary' => 'Change a note (only the fields sent)',
            'request' => $input,
            'response' => $note,
            'errors' => [401, 403, 404, 422],
        ]);
        $api->delete('/notes/{id:\d+}', [NotesApi::class, 'destroy'], permission: self::CAPABILITY, options: [
            'summary' => 'Delete a note',
            'errors' => [401, 403, 404],
        ]);
    }

    /**
     * @return array<string, mixed>
     */
    private static function dynamicBlock(PluginContext $context): array
    {
        return [
            'label' => 'plugin::prime-starter.dynamic.label',
            'description' => 'plugin::prime-starter.dynamic.description',
            'defaults' => ['title' => t('plugin::prime-starter.dynamic.default_title'), 'limit' => 3],
            'fields' => [
                ['name' => 'title', 'type' => 'text', 'label' => 'plugin::prime-starter.dynamic.title', 'default' => t('plugin::prime-starter.dynamic.default_title')],
                ['name' => 'limit', 'type' => 'number', 'label' => 'plugin::prime-starter.dynamic.limit', 'min' => 1, 'max' => 10, 'step' => 1, 'default' => 3],
            ],
            'render' => static function (array $attrs) use ($context): string {
                try {
                    $limit = is_numeric($attrs['limit'] ?? null) ? max(1, min(10, (int) $attrs['limit'])) : 3;
                    $notes = $context->app()->get(NoteRepository::class)->all(publicOnly: true, limit: $limit);
                } catch (Throwable) {
                    return '';
                }
                if ($notes === []) {
                    return '';
                }

                $e = static fn (string $v): string => htmlspecialchars($v, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
                $title = is_string($attrs['title'] ?? null) ? trim($attrs['title']) : '';
                $html = '<section class="prime-dyn prime-dyn--starter-notes">';
                if ($title !== '') {
                    $html .= '<h3 class="prime-dyn__title">' . $e($title) . '</h3>';
                }
                $html .= '<ul class="prime-starter-mini">';
                foreach ($notes as $note) {
                    $html .= '<li><a href="' . $e(self::PUBLIC_PATH . '#note-' . $note['id']) . '">' . $e($note['title']) . '</a></li>';
                }

                return $html . '</ul></section>';
            },
        ];
    }
}
