<?php

declare(strict_types=1);

namespace HelloPrime;

use Closure;
use HelloPrime\Controller\HelloPrimeController;
use Prime\Admin\AdminContext;
use Prime\Admin\Menu\AdminMenu;
use Prime\Admin\Menu\MenuItem;
use Prime\Admin\Notice;
use Prime\Auth\Auth;
use Prime\Auth\User;
use Prime\Content\ContentType;
use Prime\Content\Entry;
use Prime\Content\EntryQuery;
use Prime\Content\EntryRepository;
use Prime\Content\Fields\Field;
use Prime\Content\Fields\FieldGroup;
use Prime\Content\Taxonomy;
use Prime\Content\TermRepository;
use Prime\Editor\BlockDefinition;
use Prime\Http\Router;
use Prime\Media\Media;
use Prime\Plugins\AbstractPlugin;
use Prime\Plugins\PluginContext;
use Prime\Security\HtmlSanitizer;
use Prime\Settings\SettingsRegistry;
use Throwable;

/**
 * Reference plugin exercising the entire official Prime CMS PluginContext API
 * (menus, capabilities, settings, migrations, routes, notices, custom content types,
 * taxonomies, custom fields, custom Prime Editor blocks, and traceless uninstall)
 * without touching core internals.
 */
final class Plugin extends AbstractPlugin
{
    public const CAPABILITY_MANAGE = 'hello_prime.manage';
    public const DEFAULT_GREETING = 'Bonjour depuis Hello Prime !';
    public const CPT_TESTIMONIAL = 'testimonial';
    public const TAX_SOURCE = 'testimonial_source';
    public const BLOCK_HIGHLIGHT = 'hello-prime/highlight';

    public function register(PluginContext $context): void
    {
        // 0. « Message d'accueil » section on « Réglages › Général », generated by the settings API.
        $context->hooks()->filter('settings.register', static function (mixed $registry): mixed {
            if ($registry instanceof SettingsRegistry) {
                $registry->section('hello-prime', [
                    'label' => 'plugin::hello-prime.settings.section_title',
                    'description' => 'plugin::hello-prime.settings.section_description',
                    'icon' => 'sparkles',
                    'priority' => 200,
                    'page' => 'general',
                ]);
                $registry->add([
                    'name' => 'plugin.hello-prime.greeting',
                    'label' => 'plugin::hello-prime.settings.greeting_label',
                    'description' => 'plugin::hello-prime.settings.greeting_help',
                    'type' => 'text',
                    'section' => 'hello-prime',
                    'default' => self::DEFAULT_GREETING,
                    'rules' => 'required|max:160',
                    'priority' => 10,
                ], 'hello-prime');
            }

            return $registry;
        });

        // 1. Register custom capability grouped under "Hello Prime"
        $context->capabilities()->register(
            self::CAPABILITY_MANAGE,
            'plugin::hello-prime.capability',
        );

        // 2. Register custom Content Type ("Témoignages")
        $context->contentTypes()->register(new ContentType(
            name: self::CPT_TESTIMONIAL,
            labels: [
                'singular' => 'plugin::hello-prime.types.testimonial.singular',
                'plural' => 'plugin::hello-prime.types.testimonial.plural',
                'add_new' => 'plugin::hello-prime.types.testimonial.add_new',
                'edit' => 'plugin::hello-prime.types.testimonial.edit',
                'empty_title' => 'plugin::hello-prime.types.testimonial.empty_title',
                'empty_description' => 'plugin::hello-prime.types.testimonial.empty_description',
                'search_placeholder' => 'plugin::hello-prime.types.testimonial.search_placeholder',
            ],
            icon: 'star',
            accent: 'violet',
            hierarchical: false,
            public: true,
            supports: ['editor', 'excerpt', 'author', 'revisions', 'custom_fields', 'thumbnail'],
            taxonomies: [self::TAX_SOURCE],
            menuPosition: 35,
            rewriteBase: 'temoignages',
        ));

        // 3. Register custom Taxonomy ("Sources") attached to `testimonial`
        $context->taxonomies()->register(new Taxonomy(
            name: self::TAX_SOURCE,
            labels: [
                'singular' => 'plugin::hello-prime.types.source.singular',
                'plural' => 'plugin::hello-prime.types.source.plural',
                'add_new' => 'plugin::hello-prime.types.source.add_new',
                'empty_title' => 'plugin::hello-prime.types.source.empty_title',
            ],
            hierarchical: false,
            contentTypes: [self::CPT_TESTIMONIAL],
            public: true,
            icon: 'tag',
        ));

        // 4. Register Custom Field Group attached to `testimonial`
        $context->fields()->registerGroup(new FieldGroup(
            id: 'hello-prime.testimonial_details',
            title: 'plugin::hello-prime.fields.group_title',
            contentTypes: [self::CPT_TESTIMONIAL],
            fields: [
                new Field(
                    name: 'author_role',
                    type: 'text',
                    label: 'plugin::hello-prime.fields.author_role',
                    placeholder: 'plugin::hello-prime.fields.author_role_placeholder',
                ),
                new Field(
                    name: 'rating',
                    type: 'number',
                    label: 'plugin::hello-prime.fields.rating',
                    default: 5,
                    min: 1.0,
                    max: 5.0,
                    step: 1.0,
                ),
                new Field(
                    name: 'author_photo',
                    type: 'media',
                    label: 'plugin::hello-prime.fields.author_photo',
                    description: 'plugin::hello-prime.fields.author_photo_help',
                    mediaKinds: ['image'],
                ),
                new Field(
                    name: 'featured',
                    type: 'checkbox',
                    label: 'plugin::hello-prime.fields.featured',
                    default: false,
                ),
            ],
            location: FieldGroup::LOCATION_SIDEBAR,
            order: 15,
            description: 'plugin::hello-prime.fields.group_description',
        ));

        // 5. Register custom Prime Editor block (`hello-prime/highlight`) + client module
        $context->blocks()->register(new BlockDefinition(
            type: self::BLOCK_HIGHLIGHT,
            title: 'plugin::hello-prime.blocks.highlight.title',
            description: 'plugin::hello-prime.blocks.highlight.description',
            icon: 'sparkles',
            category: 'plugins',
            validator: static function (array $data, HtmlSanitizer $sanitizer): array {
                $badge = is_string($data['badge'] ?? null) ? trim($data['badge']) : 'À retenir';
                $badge = mb_substr($badge, 0, 60);
                $text = is_string($data['text'] ?? null) ? $sanitizer->sanitizeInline($data['text']) : '';

                return [
                    'data' => [
                        'badge' => $badge !== '' ? $badge : 'À retenir',
                        'text' => $text,
                    ],
                    'errors' => [],
                ];
            },
            renderer: static function (array $data, HtmlSanitizer $sanitizer): string {
                $badge = is_string($data['badge'] ?? null) ? trim($data['badge']) : 'À retenir';
                $text = is_string($data['text'] ?? null) ? $sanitizer->sanitizeInline($data['text']) : '';

                return '<aside class="pc-block pc-block--hello-highlight">'
                    . '<span class="pc-hello-highlight__badge">' . htmlspecialchars($badge, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '</span>'
                    . '<div class="pc-hello-highlight__body">' . $text . '</div>'
                    . '</aside>';
            },
            textExtractor: static function (array $data): string {
                $badge = is_string($data['badge'] ?? null) ? trim($data['badge']) : '';
                $text = is_string($data['text'] ?? null) ? trim(strip_tags($data['text'])) : '';

                return trim($badge . ' ' . $text);
            },
            keywords: ['highlight', 'spotlight', 'hello', 'encart', 'violet'],
        ));
        $context->blocks()->enqueueScript($context->url('js/highlight-block.js'));

        // 6. Register controller in container using PluginContext dependencies
        $context->app()->container()->singleton(
            HelloPrimeController::class,
            static function () use ($context): HelloPrimeController {
                /** @var AdminContext $adminContext */
                $adminContext = $context->app()->make(AdminContext::class);
                /** @var Auth $auth */
                $auth = $context->app()->make(Auth::class);

                return new HelloPrimeController($context, $adminContext, $auth);
            },
        );

        // 7. Add sidebar menu item (violet accent) via `admin.menu` filter
        $context->hooks()->filter('admin.menu', static function (mixed $menu): mixed {
            if ($menu instanceof AdminMenu) {
                $menu->add(new MenuItem(
                    id: 'plugin.hello-prime',
                    label: 'Hello Prime',
                    icon: 'sparkles',
                    url: '/admin/hello-prime',
                    position: 62,
                    accent: 'violet',
                    capability: self::CAPABILITY_MANAGE,
                    group: 'admin.menu.groups.system',
                ));
            }

            return $menu;
        });

        // 8. Register plugin stylesheet via `admin.assets` filter
        $context->hooks()->filter('admin.assets', static function (mixed $assets) use ($context): mixed {
            if (is_array($assets) && isset($assets['css']) && is_array($assets['css'])) {
                $assets['css'][] = $context->url('css/hello-prime.css');
            }

            return $assets;
        });

        // 9. Add a dashboard shortcut tile via `admin.dashboard.shortcuts` filter
        $context->hooks()->filter('admin.dashboard.shortcuts', static function (mixed $shortcuts, mixed $user): mixed {
            if (!is_array($shortcuts)) {
                return $shortcuts;
            }
            if ($user instanceof User && !$user->can(self::CAPABILITY_MANAGE)) {
                return $shortcuts;
            }

            $shortcuts[] = [
                'title' => 'Hello Prime',
                'description' => t('plugin::hello-prime.ui.shortcut'),
                'icon' => 'sparkles',
                'accent' => 'violet',
                'url' => '/admin/hello-prime',
            ];

            return $shortcuts;
        });

        // 10. Declare settings shortcut URL for `/admin/plugins`
        $context->setSettingsUrl('/admin/hello-prime');

        // 11. Register protected admin routes (`/admin/hello-prime/*`)
        $context->router()->adminGroup(static function (Router $r): void {
            $r->get('/', [HelloPrimeController::class, 'adminIndex'])->name('index');
            $r->post('/greetings', [HelloPrimeController::class, 'addGreeting'])->name('greetings.store');
            $r->post('/greetings/{id:\d+}/delete', [HelloPrimeController::class, 'deleteGreeting'])->name('greetings.delete');
        }, capability: self::CAPABILITY_MANAGE);

        // 12. Register public front-office route (`GET /hello-prime`)
        $context->router()->frontGroup(static function (Router $r): void {
            $r->get('/hello-prime', [HelloPrimeController::class, 'publicPage'])->name('public');
        });

        // 13. Observe `media.uploaded` lifecycle event (Phase 7 example)
        $context->hooks()->on('media.uploaded', static function (mixed $media) use ($context): void {
            if ($media instanceof Media) {
                $context->logger()->info(sprintf('Hello Prime : nouveau média détecté (#%d — %s)', $media->id, $media->originalName));
            }
        });

        // 14. Register dynamic block `hello_testimonial` via `blocks.dynamic` (Phase 8 L12 + Revue 1 C2)
        $context->hooks()->filter('blocks.dynamic', function (mixed $blocks) use ($context): mixed {
            if (!is_array($blocks)) {
                return $blocks;
            }

            $blocks['hello_testimonial'] = [
                'label' => 'plugin::hello-prime.dynamic.label',
                'description' => 'plugin::hello-prime.dynamic.description',
                'defaults' => [
                    'title' => t('plugin::hello-prime.dynamic.default_title'),
                    'min_rating' => 1,
                    'show_stars' => true,
                    'style' => 'card',
                ],
                'fields' => [
                    [
                        'name' => 'title',
                        'type' => 'text',
                        'label' => 'plugin::hello-prime.dynamic.title',
                        'placeholder' => t('plugin::hello-prime.dynamic.default_title'),
                        'default' => t('plugin::hello-prime.dynamic.default_title'),
                    ],
                    [
                        'name' => 'min_rating',
                        'type' => 'number',
                        'label' => 'plugin::hello-prime.dynamic.min_rating',
                        'min' => 1,
                        'max' => 5,
                        'step' => 1,
                        'default' => 1,
                    ],
                    [
                        'name' => 'show_stars',
                        'type' => 'toggle',
                        'label' => 'plugin::hello-prime.dynamic.show_stars',
                        'default' => true,
                    ],
                    [
                        'name' => 'style',
                        'type' => 'select',
                        'label' => 'plugin::hello-prime.dynamic.style',
                        'options' => [
                            ['value' => 'card', 'label' => 'plugin::hello-prime.dynamic.style_card'],
                            ['value' => 'compact', 'label' => 'plugin::hello-prime.dynamic.style_compact'],
                        ],
                        'default' => 'card',
                    ],
                ],
                'render' => $this->createTestimonialRenderer($context),
            ];

            return $blocks;
        });

        // 15. Provide fallback archive template `archive/testimonial.php` via `site.template_paths` (Phase 8 L12)
        $pluginTemplatesDir = dirname(__DIR__) . '/templates';
        $context->hooks()->filter('site.template_paths', static function (mixed $paths) use ($pluginTemplatesDir): mixed {
            if (!is_array($paths)) {
                return $paths;
            }
            if (is_dir($pluginTemplatesDir) && !in_array($pluginTemplatesDir, $paths, true)) {
                $paths[] = $pluginTemplatesDir;
            }

            return $paths;
        });
    }

    public function activate(PluginContext $context): void
    {
        if (!$context->settings()->has('greeting')) {
            $context->settings()->set('greeting', self::DEFAULT_GREETING);
        }

        $context->notices()->add(
            id: 'welcome',
            type: Notice::TYPE_SUCCESS,
            title: 'plugin::hello-prime.notices.welcome.title',
            message: 'plugin::hello-prime.notices.welcome.message',
            actionLabel: 'plugin::hello-prime.notices.welcome.action',
            actionUrl: '/admin/hello-prime',
            capability: self::CAPABILITY_MANAGE,
            dismissible: true,
        );

        $context->logger()->info('Plugin Hello Prime activé.');
    }

    public function deactivate(PluginContext $context): void
    {
        $context->notices()->remove('welcome');
        $context->logger()->info('Plugin Hello Prime désactivé.');
    }

    public function uninstall(PluginContext $context): void
    {
        $context->notices()->clearAll();

        // Traceless cleanup of all `testimonial` entries & `testimonial_source` terms
        try {
            if ($context->app()->container()->has(EntryRepository::class)) {
                /** @var EntryRepository $entries */
                $entries = $context->app()->get(EntryRepository::class);
                $entries->deleteByType(self::CPT_TESTIMONIAL);
            }
            if ($context->app()->container()->has(TermRepository::class)) {
                /** @var TermRepository $terms */
                $terms = $context->app()->get(TermRepository::class);
                $terms->deleteByTaxonomy(self::TAX_SOURCE);
            }
        } catch (Throwable) {
            // Content tables may not exist in lightweight unit test harnesses.
        }

        $context->logger()->info('Plugin Hello Prime désinstallé : nettoyage complet terminé.');
    }

    /**
     * Build the typed dynamic block renderer closure for `hello_testimonial`.
     *
     * @return Closure(array<string, mixed>): string
     */
    private function createTestimonialRenderer(PluginContext $context): Closure
    {
        return static function (array $attrs) use ($context): string {
            if (!$context->app()->container()->has(EntryQuery::class)) {
                return '';
            }

            try {
                /** @var EntryQuery $query */
                $query = $context->app()->get(EntryQuery::class);
                $items = $query->newQuery()
                    ->type(self::CPT_TESTIMONIAL)
                    ->orderBy('published_at', 'DESC')
                    ->limit(25)
                    ->get();
                if ($items === []) {
                    return '';
                }

                $minRating = is_numeric($attrs['min_rating'] ?? null)
                    ? max(1, min(5, (int) $attrs['min_rating']))
                    : 1;
                $eligible = array_values(array_filter(
                    $items,
                    static function (Entry $item) use ($minRating): bool {
                        $raw = $item->meta('rating');
                        $r = is_numeric($raw) ? (int) $raw : 5;

                        return $r >= $minRating;
                    },
                ));
                $pool = $eligible !== [] ? $eligible : $items;

                $chosen = $pool[random_int(0, count($pool) - 1)];
                $e = static fn (string $v): string => htmlspecialchars($v, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
                $heading = is_string($attrs['title'] ?? null) ? trim($attrs['title']) : '';
                $rawShowStars = $attrs['show_stars'] ?? true;
                $showStars = $rawShowStars !== false && $rawShowStars !== '0' && $rawShowStars !== 0;
                $style = ($attrs['style'] ?? 'card') === 'compact' ? 'compact' : 'card';

                $rawRole = $chosen->meta('author_role');
                $role = is_string($rawRole) ? trim($rawRole) : '';
                $rawRating = $chosen->meta('rating');
                $rating = is_numeric($rawRating) ? max(1, min(5, (int) $rawRating)) : 5;
                $stars = str_repeat('★', $rating) . str_repeat('☆', 5 - $rating);
                $quote = $chosen->excerpt !== null && trim($chosen->excerpt) !== ''
                    ? trim($chosen->excerpt)
                    : trim($chosen->contentText);

                $modifier = $style === 'compact' ? ' aurora-testimonial--compact' : '';
                $html = '<section class="prime-dyn prime-dyn--hello-testimonial aurora-testimonial' . $modifier . '">';
                if ($heading !== '') {
                    $html .= '<h3 class="prime-dyn__title">' . $e($heading) . '</h3>';
                }
                if ($showStars) {
                    $html .= '<div class="aurora-testimonial__stars" aria-label="Note : ' . $rating . ' sur 5">' . $stars . '</div>';
                }
                $html .= '<blockquote class="aurora-testimonial__quote">' . $e($quote) . '</blockquote>';
                $html .= '<footer class="aurora-testimonial__author">' . $e($chosen->title);
                if ($role !== '') {
                    $html .= '<span class="aurora-testimonial__role">' . $e($role) . '</span>';
                }
                $html .= '</footer></section>';

                return $html;
            } catch (Throwable) {
                return '';
            }
        };
    }
}
